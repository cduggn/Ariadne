# deploy/serving.json, not this file. The committed deploy/k8s/vllm.yaml is the default pair; a test keeps it in sync.
#
# vLLM workers: a StatefulSet so each worker has a stable name (vllm-0, vllm-1) the gateway can pick by; a headless
# Service gives each one DNS (vllm-0.vllm.default.svc). Cluster-internal only: no hostPort, no NodePort, no
# LoadBalancer. Reach it with `make tunnel`.
#
# Model {name}: {summary}.
# Topology {topo}: {purpose}.
# Each replica gets {gpumem:,} MiB and {cores} % of the SMs through HAMi; at most {max_replicas} replica(s). Start with 1;
# `make scale N=...` adds workers. Fit: `make fit MODEL={name} TOPO={topo}`.
