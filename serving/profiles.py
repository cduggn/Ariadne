PREFETCH = """\
#!/usr/bin/env bash
# GENERATED by serving/profiles.py: fetch {repo}@{revision} into the node's HF cache (run as root on the node).
# The same container and marker as the boot-time fetch in deploy/cloud-init.yaml, so nothing is downloaded twice.
set -euo pipefail
MARK=/var/lib/bootstrap/model-{revision}
if [ -f "$MARK" ]; then echo "already fetched: {repo}@{revision}"; exit 0; fi
mkdir -p /opt/hf-cache
k3s ctr -n k8s.io run --rm --net-host \\
  --mount "type=bind,src=/opt/hf-cache,dst=/root/.cache/huggingface,options=rbind:rw" \\
  "{image}" "hf-fetch-$$" \\
  python3 -c 'from huggingface_hub import snapshot_download as d; print(d("{repo}", revision="{revision}", allow_patterns={patterns}))'
touch "$MARK"
"""


def topology(s: dict, topo: str) -> dict:
    if topo not in s["topologies"]:
        raise SystemExit(f"no topology {topo!r}; have: {', '.join(s['topologies'])}")
    return s["topologies"][topo]


def render_manifest(p: dict, topo: str, s: dict | None = None) -> str:
    s = s or load_serving()
    t, e = topology(s, topo), s["engine"]
    return TEMPLATE.format(name=p["name"], topo=topo, summary=p["summary"], purpose=t["purpose"], gpumem=t["gpumem_mib"],
                           cores=t["gpucores"], max_replicas=t["max_replicas"], image=e["image"], repo=p["hf"]["repo"],
                           revision=p["hf"]["revision"], served=p["serve"]["served_name"], max_model_len=e["max_model_len"],
                           util=e["gpu_memory_utilization"], max_num_seqs=e["max_num_seqs"],
                           max_num_batched_tokens=e["max_num_batched_tokens"], gpu_mib=s["gpu"]["mib"],
                           model_args="\n".join(f"            - {a}" for a in p["serve"]["args"]))


def render_prefetch(p: dict, s: dict | None = None) -> str:
    s = s or load_serving()
    patterns = p["hf"].get("allow_patterns")
    return PREFETCH.format(repo=p["hf"]["repo"], revision=p["hf"]["revision"], image=s["engine"]["image"],
                           patterns=json.dumps(patterns) if patterns else "None")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list")
    r = sub.add_parser("render")
    r.add_argument("model")
    r.add_argument("topology")
    r.add_argument("--out", help="directory for k8s/vllm.yaml and prefetch.sh (default: the manifest on stdout)")
    f = sub.add_parser("field", help="print one profile field, e.g. serve.served_name")
    f.add_argument("model")
    f.add_argument("path")
    a = ap.parse_args(argv)
    if a.cmd == "list":
        for p in profiles():
            print(f"{p['name']:26} {p['plan']:10} {p['hf']['repo']}")
        return 0
    p = load_profile(a.model)
    if a.cmd == "field":
        v = p
        for k in a.path.split("."):
            v = v[k]
        print(v if isinstance(v, str) else json.dumps(v))
        return 0
    s = load_serving()
    manifest = render_manifest(p, a.topology, s)
    if not a.out:
        sys.stdout.write(manifest)
        return 0
    out = Path(a.out)
    (out / "k8s").mkdir(parents=True, exist_ok=True)
    (out / "k8s" / "vllm.yaml").write_text(manifest)
    (out / "prefetch.sh").write_text(render_prefetch(p, s))
    print(f"rendered {a.model} on {a.topology} → {out}/k8s/vllm.yaml, {out}/prefetch.sh")
    return 0


if __name__ == "__main__":
    sys.exit(main())
