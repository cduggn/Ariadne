"""The llm-d 1.0 router for one model × topology (design/llm-d.md): Helm values for llm-d-router-standalone, with the
EPP config inside, and the worker manifest it routes to. Every number comes from deploy/serving.json, the profile or
serving/fit.py, never typed in. Standard library only.

    python -m serving.llmd qwen3-8b-awq sliced --out deploy/llm-d     # values.yaml + vllm.yaml
    python -m serving.llmd qwen3-8b-awq sliced                        # values on stdout

Precise or approximate prefix routing follows the profile's attention (profiles.ROUTER_PREFIX). Flow control queues
by the two InferenceObjectives the gateway names in x-llm-d-inference-objective, and round-robins by tenant
(x-llm-d-inference-fairness-id) inside each band.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from serving import fit, profiles

HEADER = """\
# GENERATED by `python -m serving.llmd {name} {topo}` (serving/llmd.py) from deploy/serving.json (llm_d),
# deploy/models/{name}.json and serving/fit.py. A test keeps the committed copy equal to the render.
#
#   kubectl apply -f {crds}
#   helm upgrade --install {release} {chart} --version {version} -f values.yaml
#
# JSON is YAML, so Helm reads this file as is.
# Prefix routing: {mode} ({attention} attention).
# maxConcurrency {inflight} is per endpoint: the concurrency detector's pool saturation is in-flight requests over the
#   sum of every endpoint's maxConcurrency (its v1.0.0 README). It is the gateway's D-43 cap for this pair.
# peakPrefillThroughput {prefill} tokens/s is the topology's uncached prefill rate (paper until measured).
# FailOpen: with the EPP down, Envoy load-balances across the workers without flow control or prefix routing. The
#   gateway still holds the tenant quota and the refusal contract, and a single EPP replica under FailClose would
#   turn every EPP restart into an outage.
# One EPP replica: in-flight token accounting and the flow-control queues are per process.
"""


def epp_config(p: dict, r: dict, s: dict) -> dict:
    d = s["llm_d"]
    if profiles.ROUTER_PREFIX[profiles.attention(p["arch"])] == "precise":
        ev = d["kv_events"]
        plugins = [
            {"type": "token-producer", "parameters": {"modelName": p["serve"]["served_name"], "vllm": {
                "endpointDiscovery": {"attemptTimeout": "2s"}, "messagesRenderMode": "auto", "responsesRenderMode": "auto"}}},
            {"type": "endpoint-notification-source"},
            {"type": "precise-prefix-cache-producer", "parameters": {
                "tokenProcessorConfig": {"blockSizeTokens": d["block_size"], "hashAlgorithm": "xxh64"},
                "speculativeIndexing": True,
                "indexerConfig": {"kvBlockIndexConfig": {"enableMetrics": True}},
                "kvEventsConfig": {"engineType": "vllm", "topicFilter": "kv@", "concurrency": 8, "discoverPods": True,
                                   "podDiscoveryConfig": {"socketPort": ev["port"], "replaySocketPort": ev["replay_port"]}}}},
            {"type": "inflight-load-producer", "parameters": {"prefixMatchInfoProducerName": "precise-prefix-cache-producer"}},
            {"type": "prefix-cache-affinity-filter", "parameters": {
                "prefixMatchInfoProducerName": "precise-prefix-cache-producer", "peakPrefillThroughput": fit.prefill_rate(r)}},
            {"type": "token-load-scorer"},
        ]
        profile = [{"pluginRef": "prefix-cache-affinity-filter"}, {"pluginRef": "token-load-scorer"}]
        data_layer = {"sources": [{"pluginRef": "endpoint-notification-source",
                                   "extractors": [{"pluginRef": "precise-prefix-cache-producer"}]}]}
    else:
        weights = {"queue-scorer": 2, "kv-cache-utilization-scorer": 2, "prefix-cache-scorer": 3, "no-hit-lru-scorer": 2}
        plugins = [{"type": t} for t in weights]
        profile = [{"pluginRef": t, "weight": w} for t, w in weights.items()]
        data_layer = None
    plugins += [{"type": "round-robin-fairness-policy"}, {"type": "fcfs-ordering-policy"},
                {"type": "concurrency-detector",
                 "parameters": {"maxConcurrency": fit.max_inflight(r), "concurrencyMode": "requests", "headroom": 0.0}}]
    objectives = d["objectives"]
    config = {
        "apiVersion": "llm-d.ai/v1", "kind": "EndpointPickerConfig", "featureGates": ["flowControl"], "plugins": plugins,
        "schedulingProfiles": [{"name": "default", "plugins": profile}],
        "flowControl": {
            "defaultRequestTTL": f"{max(o['queue_ttl_s'] for o in objectives)}s",
            "saturationDetector": {"pluginRef": "concurrency-detector"},
            "priorityBands": [{"priority": o["priority"], "defaultRequestTTL": f"{o['queue_ttl_s']}s",
                               "fairnessPolicyRef": "round-robin-fairness-policy", "orderingPolicyRef": "fcfs-ordering-policy"}
                              for o in objectives],
        },
    }
    if data_layer:
        config["dataLayer"] = data_layer
    return config


def values(p: dict, r: dict, s: dict) -> dict:
    d = s["llm_d"]
    image, tag = d["epp_image"].rsplit(":", 1)
    registry, repository = image.rsplit("/", 1)
    return {"router": {
        "modelServers": {"type": "vllm", "protocol": "http", "targetPorts": [{"number": 8000}], "matchLabels": {"app": "vllm"}},
        "inferencePool": {"create": True, "failureMode": "FailOpen"},
        # The chart renders these as llm-d.ai/v1alpha2 with poolRef, the schema its v1.0.0 guides ship; v1 (poolRefs) is unverified.
        "inferenceObjectives": [{"name": o["name"], "priority": o["priority"]} for o in d["objectives"]],
        "proxy": {"enabled": True, "proxyType": "envoy", "mode": "service", "replicas": 1, "failOpen": True,
                  "resources": {"requests": {"cpu": "1", "memory": "1Gi"}, "limits": {"memory": "2Gi"}}},
        "epp": {
            "replicas": 1,
            "image": {"registry": registry, "repository": repository, "tag": tag, "pullPolicy": "IfNotPresent"},
            "resources": {"requests": {"cpu": "2", "memory": "4Gi"}, "limits": {"memory": "8Gi"}},
            "pluginsConfigFile": "doctor-plugins.yaml",
            "pluginsConfig": epp_config(p, r, s),
        },
    }}


def render_values(p: dict, topo: str, s: dict | None = None) -> str:
    s = s or profiles.load_serving()
    d, r = s["llm_d"], fit.fit(p, topo, s)
    head = HEADER.format(name=p["name"], topo=topo, crds=" -f ".join(d["crds"]), release=d["release"], chart=d["chart"],
                         version=d["chart_version"], mode=profiles.ROUTER_PREFIX[profiles.attention(p["arch"])],
                         attention=profiles.attention(p["arch"]), inflight=fit.max_inflight(r), prefill=fit.prefill_rate(r))
    return head + json.dumps(values(p, r, s), indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("model")
    ap.add_argument("topology")
    ap.add_argument("--out", help="directory for values.yaml and vllm.yaml (default: the values on stdout)")
    a = ap.parse_args(argv)
    p, s = profiles.load_profile(a.model), profiles.load_serving()
    text = render_values(p, a.topology, s)
    if not a.out:
        sys.stdout.write(text)
        return 0
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "values.yaml").write_text(text)
    (out / "vllm.yaml").write_text(profiles.render_manifest(p, a.topology, s, llmd=True))
    print(f"rendered the llm-d router for {a.model} on {a.topology} → {out}/values.yaml, {out}/vllm.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
